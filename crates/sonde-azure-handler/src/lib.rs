/// Error from program ingestion with HTTP status code.
#[derive(Debug)]
pub struct IngestError {
    pub status_code: u16,
    pub message: String,
}

impl IngestError {
    fn bad_request(msg: impl Into<String>) -> Self {
        Self {
            status_code: 400,
            message: msg.into(),
        }
    }

    fn payload_too_large(msg: impl Into<String>) -> Self {
        Self {
            status_code: 413,
            message: msg.into(),
        }
    }

    fn unprocessable(msg: impl Into<String>) -> Self {
        Self {
            status_code: 422,
            message: msg.into(),
        }
    }

    fn internal(msg: impl Into<String>) -> Self {
        Self {
            status_code: 500,
            message: msg.into(),
        }
    }
}

impl std::fmt::Display for IngestError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "HTTP {}: {}", self.status_code, self.message)
    }
}

fn chrono_iso8601_utc_now() -> String {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default();
    let secs = now.as_secs();
    let days = secs / 86400;
    let time_of_day = secs % 86400;
    let hours = time_of_day / 3600;
    let minutes = (time_of_day % 3600) / 60;
    let seconds = time_of_day % 60;

    // Compute year/month/day from days since epoch (1970-01-01).
    let mut y = 1970i64;
    let mut remaining = days as i64;
    loop {
        let days_in_year = if y % 4 == 0 && (y % 100 != 0 || y % 400 == 0) {
            366
        } else {
            365
        };
        if remaining < days_in_year {
            break;
        }
        remaining -= days_in_year;
        y += 1;
    }
    let leap = y % 4 == 0 && (y % 100 != 0 || y % 400 == 0);
    let month_days: [i64; 12] = [
        31,
        if leap { 29 } else { 28 },
        31,
        30,
        31,
        30,
        31,
        31,
        30,
        31,
        30,
        31,
    ];
    let mut m = 0;
    for &md in &month_days {
        if remaining < md {
            break;
        }
        remaining -= md;
        m += 1;
    }
    format!(
        "{:04}-{:02}-{:02}T{:02}:{:02}:{:02}Z",
        y,
        m + 1,
        remaining + 1,
        hours,
        minutes,
        seconds
    )
}

/// Extract the JSON body from an Azure Functions HTTP trigger invocation
/// envelope. The envelope is the outer JSON sent by the Functions host when
/// `enableForwardingHttpRequest` is `false`.
///
/// Returns the parsed body as a `serde_json::Value`.
pub fn extract_http_trigger_body(request_body: &[u8]) -> Result<serde_json::Value, HandlerError> {
    let envelope: serde_json::Value = serde_json::from_slice(request_body)?;
    let body_str = envelope
        .get("Data")
        .or_else(|| envelope.get("data"))
        .and_then(|data| data.get("req").or_else(|| data.get("Req")))
        .and_then(|req| req.get("Body").or_else(|| req.get("body")))
        .and_then(|v| v.as_str())
        .ok_or_else(|| {
            HandlerError::Decode("HTTP trigger envelope missing `Data.req.Body`".to_string())
        })?;
    serde_json::from_str(body_str)
        .map_err(|e| HandlerError::Decode(format!("HTTP trigger body is not valid JSON: {e}")))
}

/// Format an `IngestResponse` as an Azure Functions HTTP output binding
/// response envelope. The binding name `res` matches
/// `ProgramIngest/function.json`.
pub fn format_ingest_response(status_code: u16, body: &serde_json::Value) -> serde_json::Value {
    serde_json::json!({
        "Outputs": {
            "res": {
                "statusCode": status_code,
                "headers": {"Content-Type": "application/json"},
                "body": serde_json::to_string(body).unwrap_or_default()
            }
        }
    })
}

/// Workaround for azure-sdk-for-rust#4489: some Azure Table Storage stamps
/// omit the `Server` HTTP response header, but `azure_storage` 0.21.0
/// `CommonStorageResponseHeaders` unconditionally requires it, failing with
/// `"header not found server"`. This policy injects a synthetic header when
/// one is missing so the SDK's response parsing succeeds.
#[derive(Debug)]
struct InjectServerHeaderPolicy;

#[async_trait]
impl azure_core_legacy::Policy for InjectServerHeaderPolicy {
    async fn send(
        &self,
        ctx: &azure_core_legacy::Context,
        request: &mut azure_core_legacy::Request,
        next: &[Arc<dyn azure_core_legacy::Policy>],
    ) -> azure_core_legacy::PolicyResult {
        let response = next[0].send(ctx, request, &next[1..]).await?;
        if response
            .headers()
            .get_optional_str(&azure_core_legacy::headers::SERVER)
            .is_none()
        {
            // Deconstruct, inject, reconstruct — Response has no headers_mut().
            let (status, mut headers, body) = response.deconstruct();
            headers.insert(
                azure_core_legacy::headers::SERVER,
                "Windows-Azure-Table/1.0 Microsoft-HTTPAPI/2.0",
            );
            Ok(azure_core_legacy::Response::new(
                status,
                headers,
                Box::pin(body),
            ))
        } else {
            Ok(response)
        }
    }
}

